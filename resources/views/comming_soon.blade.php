  <script>
    const countdownKey = "gpt_group_coming_soon_7_days_end_time";
    const totalDuration = 7 * 24 * 60 * 60 * 1000;

    let endTime = localStorage.getItem(countdownKey);

    if (!endTime) {
      endTime = Date.now() + totalDuration;
      localStorage.setItem(countdownKey, String(endTime));
    } else {
      endTime = Number(endTime);
    }

    const daysElement = document.getElementById("days");
    const hoursElement = document.getElementById("hours");
    const minutesElement = document.getElementById("minutes");
    const secondsElement = document.getElementById("seconds");
    const countdownWrapper = document.getElementById("countdownWrapper");
    const launchComplete = document.getElementById("launchComplete");
    const progressBar = document.getElementById("progressBar");
    const progressLabel = document.getElementById("progressLabel");

    function padNumber(value) {
      return String(value).padStart(2, "0");
    }

    function updateCountdown() {
      const now = Date.now();
      const distance = Number(endTime) - now;

      if (distance <= 0) {
        daysElement.textContent = "00";
        hoursElement.textContent = "00";
        minutesElement.textContent = "00";
        secondsElement.textContent = "00";

        countdownWrapper.classList.add("hidden");
        launchComplete.classList.remove("hidden");

        progressBar.style.width = "100%";
        progressLabel.textContent = "100%";

        return false;
      }

      const days = Math.floor(distance / (1000 * 60 * 60 * 24));
      const hours = Math.floor((distance / (1000 * 60 * 60)) % 24);
      const minutes = Math.floor((distance / (1000 * 60)) % 60);
      const seconds = Math.floor((distance / 1000) % 60);

      daysElement.textContent = padNumber(days);
      hoursElement.textContent = padNumber(hours);
      minutesElement.textContent = padNumber(minutes);
      secondsElement.textContent = padNumber(seconds);

      const elapsed = totalDuration - distance;
      let progress = Math.round((elapsed / totalDuration) * 100);

      progress = Math.max(0, Math.min(100, progress));

      progressBar.style.width = progress + "%";
      progressLabel.textContent = progress + "%";

      return true;
    }

    function showMessage() {
      const emailInput = document.getElementById("emailInput");
      const formMessage = document.getElementById("formMessage");

      if (emailInput.value.trim() !== "") {
        formMessage.classList.remove("hidden");
        emailInput.value = "";
      }
    }

    document.getElementById("year").textContent = new Date().getFullYear();

    updateCountdown();

    const interval = setInterval(function () {
      const shouldContinue = updateCountdown();

      if (!shouldContinue) {
        clearInterval(interval);
      }
    }, 1000);
  </script>

